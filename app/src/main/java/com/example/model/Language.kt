enum class AppLanguage(val code: String, val displayName: String, val flag: String) {
    FR("fr", "Français", "🇫🇷"),
    HT("ht", "Kreyòl Ayisyen", "🇭🇹"),
    EN("en", "English", "🇺🇸");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.find { it.code.equals(code, ignoreCase = true) } ?: FR
    }
}

object Strings {
    fun get(key: String, lang: AppLanguage, vararg args: Any): String {
        val map = when (lang) {
            AppLanguage.FR -> frStrings
            AppLanguage.HT -> htStrings
            AppLanguage.EN -> enStrings
        }
        var text = map[key] ?: frStrings[key] ?: key
        args.forEachIndexed { index, arg ->
            text = text.replace("{$index}", arg.toString())
        }
        return text
    }

